import mongoose from "mongoose";
import {
  EVALUATION_STATUSES,
  EVALUATION_STATUS_VALUES,
  VERIFICATION_KINDS,
  VERIFICATION_KIND_VALUES,
  VERIFICATION_SOURCES,
  VERIFICATION_SOURCE_VALUES,
} from "../../common/constants/statuses.js";

const { Schema } = mongoose;

const bboxSchema = new Schema(
  {
    x: { type: Number, required: true, min: 0, max: 1 },
    y: { type: Number, required: true, min: 0, max: 1 },
    w: { type: Number, required: true, min: 0, max: 1 },
    h: { type: Number, required: true, min: 0, max: 1 },
  },
  { _id: false }
);

const evidenceSchema = new Schema(
  {
    document: {
      type: Schema.Types.ObjectId,
      ref: "Document",
      required: true,
    },
    page: {
      type: Number,
      required: true,
      min: 1,
    },
    bbox: {
      type: bboxSchema,
      required: true,
    },
    snippet: {
      type: String,
      trim: true,
    },
  },
  { _id: false }
);

const verificationRecordSchema = new Schema(
  {
    kind: {
      type: String,
      enum: VERIFICATION_KIND_VALUES,
      required: true,
    },
    result: {
      type: String,
      trim: true,
    },
    details: {
      type: Schema.Types.Mixed,
      default: {},
    },
    source: {
      type: String,
      enum: VERIFICATION_SOURCE_VALUES,
      default: VERIFICATION_SOURCES.MOCK,
    },
    checkedAt: {
      type: Date,
      default: Date.now,
    },
  },
  { _id: false }
);

const clauseEvaluationSchema = new Schema(
  {
    tender: {
      type: Schema.Types.ObjectId,
      ref: "Tender",
      required: [true, "Tender reference is required"],
    },

    bid: {
      type: Schema.Types.ObjectId,
      ref: "Bid",
      required: [true, "Bid reference is required"],
    },

    clause: {
      type: Schema.Types.ObjectId,
      ref: "Clause",
      required: [true, "Clause reference is required"],
    },

    status: {
      type: String,
      enum: EVALUATION_STATUS_VALUES,
      default: EVALUATION_STATUSES.PENDING,
      required: true,
    },

    // Extracted primary value (e.g. "₹28.4 Cr" or "Class-I (64%)")
    extractedValue: {
      type: String,
      trim: true,
    },

    // Key-value pairs extracted from evidence
    extractedFields: {
      type: Schema.Types.Mixed,
      default: {},
    },

    // Formula or quantitative evaluation breakdown
    calculation: {
      type: Schema.Types.Mixed,
      default: {},
    },

    // Explanation / justification generated by AI engine
    reasoning: {
      type: String,
    },

    // Confidence score between 0 and 1
    confidence: {
      type: Number,
      min: 0,
      max: 1,
      default: 0,
    },

    // Snippets with bounding boxes on document pages
    evidence: {
      type: [evidenceSchema],
      default: [],
    },

    // External registry checks (GST, Udyam, UDIN, DSC)
    verification: {
      type: [verificationRecordSchema],
      default: [],
    },

    // Manual officer override
    overridden: {
      type: Boolean,
      default: false,
    },

    overrideReason: {
      type: String,
    },

    overriddenBy: {
      type: Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
  },
  { timestamps: true }
);

// ── Indexes ───────────────────────────────────────────────────────────────────
// Each bid can have exactly one evaluation per clause
clauseEvaluationSchema.index({ bid: 1, clause: 1 }, { unique: true });
// Matrix queries: load all evaluations for a tender
clauseEvaluationSchema.index({ tender: 1 });
// Filter evaluations for a specific bid by compliance status
clauseEvaluationSchema.index({ bid: 1, status: 1 });
// Find all bids evaluated against a specific clause
clauseEvaluationSchema.index({ clause: 1 });

export default mongoose.model("ClauseEvaluation", clauseEvaluationSchema);
